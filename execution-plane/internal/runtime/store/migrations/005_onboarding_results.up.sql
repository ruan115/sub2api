CREATE TABLE onboarding_results (
    workflow_id VARCHAR(128) NOT NULL,
    intent_id CHAR(36) NOT NULL,
    account_id VARCHAR(128) NOT NULL,
    desired_generation BIGINT UNSIGNED NOT NULL,
    credential_lease_id VARCHAR(128) NOT NULL,
    credential_version_id VARCHAR(128) NOT NULL,
    auth_type VARCHAR(32) NOT NULL,
    email_address VARCHAR(320) NOT NULL DEFAULT '',
    organization_id VARCHAR(128) NOT NULL DEFAULT '',
    upstream_account_id VARCHAR(128) NOT NULL DEFAULT '',
    scope_text VARCHAR(1024) NOT NULL DEFAULT '',
    subscription_type VARCHAR(128) NOT NULL DEFAULT '',
    rate_limit_tier VARCHAR(128) NOT NULL DEFAULT '',
    expires_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (workflow_id),
    UNIQUE KEY uq_onboarding_results_intent (intent_id),
    UNIQUE KEY uq_onboarding_results_credential_lease (credential_lease_id),
    KEY idx_onboarding_results_account_generation (account_id, desired_generation),
    KEY idx_onboarding_results_email (email_address),
    CONSTRAINT fk_onboarding_results_workflow FOREIGN KEY (workflow_id) REFERENCES onboarding_workflows(workflow_id),
    CONSTRAINT chk_onboarding_results_generation CHECK (desired_generation > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
